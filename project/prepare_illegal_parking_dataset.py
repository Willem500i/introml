"""
Merge the Roboflow illegal parking dataset with background (legal) negatives
sampled from car-centered BDD100K crops, producing a YOLO-format dataset.

Features:
- Adds configurable negatives per split
- Moves a subset of positives into val to ensure validation has labels
- Optional resizing of negatives to 640x640
- Writes data.yaml for YOLO

Run:
  python prepare_illegal_parking_dataset.py \
    --roboflow-dir "data/illegal parking.v1i.yolov8" \
    --bdd-negative-dir data/negative_crops_cars \
    --output-dir data/illegal_parking_merged \
    --train-neg 650 --val-neg 75 --test-neg 40 \
    --val-pos 75 \
    --no-resize-negatives
"""

import argparse
import random
import shutil
from pathlib import Path
from typing import Iterable, List

from PIL import Image

CONFIG = {
    "roboflow_dir": Path("data/illegal parking.v1i.yolov8"),
    "bdd_negative_dir": Path("data/negative_crops_cars"),
    "output_dir": Path("data/illegal_parking_merged"),
    "negatives_per_split": {"train": 650, "val": 75, "test": 40},
    "val_pos_from_train": 75,
    "resize_negatives": True,
    "resize_size": (640, 640),
    "use_symlinks": True,
    "seed": 42,
}


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def list_images(root: Path) -> List[Path]:
    exts = {".jpg", ".jpeg", ".png"}
    imgs = []
    for ext in exts:
        imgs.extend(root.rglob(f"*{ext}"))
    return imgs


def copy_or_link(src: Path, dst: Path, symlink: bool) -> None:
    if dst.exists():
        return
    if symlink:
        try:
            dst.symlink_to(src.resolve())
            return
        except OSError:
            pass
    shutil.copy2(src, dst)


def resize_and_save(src: Path, dst: Path, size: tuple[int, int]) -> None:
    if dst.exists():
        return
    with Image.open(src) as im:
        im = im.convert("RGB")
        im = im.resize(size, Image.BILINEAR)
        im.save(dst)


def split_positives(cfg):
    train_images = sorted((cfg["roboflow_dir"] / "train" / "images").glob("*"))
    train_labels = sorted((cfg["roboflow_dir"] / "train" / "labels").glob("*"))
    test_images = sorted((cfg["roboflow_dir"] / "test" / "images").glob("*"))
    test_labels = sorted((cfg["roboflow_dir"] / "test" / "labels").glob("*"))

    train_pairs = {p.stem: p for p in train_images}
    train_lbl_pairs = {p.stem: p for p in train_labels}

    stems = sorted(set(train_pairs.keys()) & set(train_lbl_pairs.keys()))
    random.shuffle(stems)
    val_take = min(cfg["val_pos_from_train"], len(stems))
    val_stems = set(stems[:val_take])
    train_stems = set(stems[val_take:])

    splits = {"train": [], "val": [], "test": []}

    for stem in train_stems:
        splits["train"].append((train_pairs[stem], train_lbl_pairs[stem]))
    for stem in val_stems:
        splits["val"].append((train_pairs[stem], train_lbl_pairs[stem]))
    for img in test_images:
        lbl = cfg["roboflow_dir"] / "test" / "labels" / f"{img.stem}.txt"
        if lbl.exists():
            splits["test"].append((img, lbl))

    return splits


def write_split(splits, cfg, symlink=True):
    for split, pairs in splits.items():
        dst_root = cfg["output_dir"] / split
        ensure_dir(dst_root / "images")
        ensure_dir(dst_root / "labels")
        for img, lbl in pairs:
            copy_or_link(img, dst_root / "images" / img.name, symlink)
            copy_or_link(lbl, dst_root / "labels" / lbl.name, symlink)


def sample_negatives(cfg, split: str, n: int) -> Iterable[Path]:
    split_dir = cfg["bdd_negative_dir"] / split
    if split_dir.exists():
        pool = list_images(split_dir)
    else:
        pool = list_images(cfg["bdd_negative_dir"])
    random.shuffle(pool)
    return pool[:n]


def add_negatives(split: str, cfg) -> None:
    n = cfg["negatives_per_split"].get(split, 0)
    if n <= 0:
        return
    dst_root = cfg["output_dir"] / split
    ensure_dir(dst_root / "images")
    ensure_dir(dst_root / "labels")

    sampled = sample_negatives(cfg, split, n)
    for img in sampled:
        out_img = dst_root / "images" / img.name
        out_lbl = dst_root / "labels" / (img.stem + ".txt")
        if cfg["resize_negatives"]:
            resize_and_save(img, out_img, cfg["resize_size"])
        else:
            copy_or_link(img, out_img, cfg["use_symlinks"])
        out_lbl.write_text("")


def write_data_yaml(cfg) -> None:
    yaml_path = cfg["output_dir"] / "data.yaml"
    content = f"""# Auto-generated by prepare_illegal_parking_dataset.py
path: {cfg['output_dir']}
train: train/images
val: val/images
test: test/images

nc: 1
names: [\"illegal parking\"]
"""
    yaml_path.write_text(content)


def clear_output(path: Path):
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def main():
    parser = argparse.ArgumentParser(description="Merge illegal parking dataset with negatives.")
    parser.add_argument("--roboflow-dir", type=Path, default=CONFIG["roboflow_dir"])
    parser.add_argument("--bdd-negative-dir", type=Path, default=CONFIG["bdd_negative_dir"])
    parser.add_argument("--output-dir", type=Path, default=CONFIG["output_dir"])
    parser.add_argument("--train-neg", type=int, default=CONFIG["negatives_per_split"]["train"])
    parser.add_argument("--val-neg", type=int, default=CONFIG["negatives_per_split"]["val"])
    parser.add_argument("--test-neg", type=int, default=CONFIG["negatives_per_split"]["test"])
    parser.add_argument("--val-pos", type=int, default=CONFIG["val_pos_from_train"], help="Move this many positives from train into val.")
    parser.add_argument("--copy", action="store_true", help="Copy files instead of symlinking positives.")
    parser.add_argument("--no-resize-negatives", action="store_true", help="Do not resize negatives (defaults to resize 640x640).")
    parser.add_argument("--seed", type=int, default=CONFIG["seed"])
    args = parser.parse_args()

    cfg = {
        **CONFIG,
        "roboflow_dir": args.roboflow_dir,
        "bdd_negative_dir": args.bdd_negative_dir,
        "output_dir": args.output_dir,
        "negatives_per_split": {
            "train": args.train_neg,
            "val": args.val_neg,
            "test": args.test_neg,
        },
        "val_pos_from_train": args.val_pos,
        "use_symlinks": not args.copy,
        "resize_negatives": not args.no_resize_negatives,
        "seed": args.seed,
    }

    random.seed(cfg["seed"])
    clear_output(cfg["output_dir"])

    splits = split_positives(cfg)
    write_split(splits, cfg, symlink=cfg["use_symlinks"])

    for split in ["train", "val", "test"]:
        add_negatives(split, cfg)

    write_data_yaml(cfg)

    print("Done.")
    print(f"Merged dataset at: {cfg['output_dir']}")
    print(f"Data config: {cfg['output_dir'] / 'data.yaml'}")
    for split in ["train", "val", "test"]:
        imgs = list((cfg["output_dir"] / split / "images").glob("*"))
        lbls = list((cfg["output_dir"] / split / "labels").glob("*.txt"))
        pos = sum(1 for p in lbls if p.stat().st_size > 0)
        print(f"{split}: images={len(imgs)}, pos={pos}, neg={len(lbls)-pos}")


if __name__ == "__main__":
    main()
